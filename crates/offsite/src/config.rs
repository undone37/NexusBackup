//! Appliance configuration backups on an offsite target (docs/control-plane.md
//! "Configuration backup"): sealed bundles of `nexus-config-backup` under
//! ```text
//! config/<appliance-id>/<unix time>.bundle
//! ```
//! Retention: the newest bundle of each of the last 14 days and of each of the
//! last 12 months. With S3 Object Lock every bundle is locked for 14 days, a
//! monthly one is extended to the monthly lock (`Class::Monthly`); deleting a
//! still locked bundle only leaves a delete marker (logged, not an error).

use crate::remote::Remote;
use anyhow::{bail, Context, Result};
use chunkstore::retention::{keep, lock_until, Class, Gfs};

pub const DIR: &str = "config";
pub const DAILY: u32 = 14;
pub const MONTHLY: u32 = 12;

/// Appliance ids are generated by the scheduler: lower-case hex/dashes.
pub fn valid_id(id: &str) -> bool {
    (1..=64).contains(&id.len())
        && id
            .bytes()
            .all(|b| b.is_ascii_digit() || b.is_ascii_lowercase() || b == b'-')
}

fn gfs() -> Gfs {
    Gfs {
        recent: 0,
        daily: DAILY,
        weekly: 0,
        monthly: MONTHLY,
        yearly: 0,
    }
}

/// Bundle times of one appliance on the remote, oldest first.
pub fn list(remote: &dyn Remote, appliance: &str) -> Result<Vec<(u64, u64)>> {
    if !valid_id(appliance) {
        bail!("invalid appliance id {appliance:?}");
    }
    let mut out: Vec<(u64, u64)> = remote
        .list(&format!("{DIR}/{appliance}"))?
        .into_iter()
        .filter(|(_, _, dir)| !dir)
        .filter_map(|(n, size, _)| Some((n.strip_suffix(".bundle")?.parse().ok()?, size)))
        .collect();
    out.sort_unstable();
    Ok(out)
}

/// Appliance ids with bundles on the remote.
pub fn appliances(remote: &dyn Remote) -> Result<Vec<String>> {
    Ok(remote
        .list(DIR)?
        .into_iter()
        .filter(|(n, _, dir)| *dir && valid_id(n))
        .map(|(n, _, _)| n)
        .collect())
}

fn path(appliance: &str, time: u64) -> String {
    format!("{DIR}/{appliance}/{time}.bundle")
}

/// Uploads one bundle made at `time` and applies the retention. Returns the
/// remote path and the names deleted.
pub fn put(remote: &dyn Remote, appliance: &str, time: u64, bundle: &[u8], now: u64) -> Result<(String, Vec<String>)> {
    if !valid_id(appliance) {
        bail!("invalid appliance id {appliance:?}");
    }
    let p = path(appliance, time);
    let r = if remote.supports_locks() {
        remote.put_locked(&p, bundle, time + Class::Daily.lock_secs())
    } else {
        remote.put(&p, bundle)
    };
    match r {
        Ok(()) => {}
        // a retried job: the same bundle is already there
        Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {}
        Err(e) => return Err(e).with_context(|| format!("uploading {p}")),
    }
    Ok((p, retention(remote, appliance, now)?))
}

/// Deletes bundles outside 14 daily + 12 monthly; extends the lock of the kept ones.
pub fn retention(remote: &dyn Remote, appliance: &str, now: u64) -> Result<Vec<String>> {
    let times: Vec<u64> = list(remote, appliance)?.into_iter().map(|(t, _)| t).collect();
    let kept = keep(&times, &gfs());
    let mut deleted = Vec::new();
    for t in times {
        let p = path(appliance, t);
        match kept.get(&t) {
            Some(classes) => {
                let until = lock_until(t, classes);
                if remote.supports_locks() && until > now {
                    if let Err(e) = remote.extend_lock(&p, until) {
                        eprintln!("<4>nexus-offsite: cannot extend the lock of {p}: {e}");
                    }
                }
            }
            None => match remote.delete(&p) {
                Ok(()) => deleted.push(p),
                Err(e) => eprintln!("<4>nexus-offsite: cannot delete old configuration bundle {p}: {e}"),
            },
        }
    }
    Ok(deleted)
}

/// The newest bundle of `appliance` (or of the only appliance on the remote).
pub fn latest(remote: &dyn Remote, appliance: Option<&str>) -> Result<(String, u64, Vec<u8>)> {
    let id = match appliance {
        Some(a) => a.to_owned(),
        None => match appliances(remote)?.as_slice() {
            [one] => one.clone(),
            [] => bail!("the offsite target holds no configuration backup (config/ is empty)"),
            many => bail!(
                "the offsite target holds configuration backups of several appliances ({}): choose one",
                many.join(", ")
            ),
        },
    };
    let Some(&(t, _)) = list(remote, &id)?.last() else {
        bail!("the offsite target holds no configuration backup of appliance {id}");
    };
    let p = path(&id, t);
    let b = remote.get(&p, 0, None).with_context(|| format!("downloading {p}"))?;
    Ok((id, t, b))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::remote::LocalDir;

    const DAY: u64 = 86400;

    #[test]
    fn upload_retention_and_latest() {
        let d = tempfile::tempdir().unwrap();
        let r = LocalDir(d.path().to_owned());
        assert!(latest(&r, None).is_err());
        // one bundle a day for 400 days, two on the last day
        let end = 20_700 * DAY + 2 * 3600;
        for i in (0..400).rev() {
            let t = end - i * DAY;
            put(&r, "a1b2", t, b"x", t).unwrap();
        }
        let (_, deleted) = put(&r, "a1b2", end + 600, b"newest", end + 600).unwrap();
        assert!(deleted.contains(&path("a1b2", end)), "same day: only the newest stays");
        let left = list(&r, "a1b2").unwrap();
        // 14 days + 12 months (the newest day is both)
        assert!(left.len() >= 24 && left.len() <= 26, "{}", left.len());
        assert_eq!(left.last().unwrap().0, end + 600);
        assert!(left.first().unwrap().0 >= end - 366 * DAY);
        // retried upload of the same bundle is fine
        put(&r, "a1b2", end + 600, b"newest", end + 600).unwrap();

        let (id, t, b) = latest(&r, None).unwrap();
        assert_eq!((id.as_str(), t, b.as_slice()), ("a1b2", end + 600, &b"newest"[..]));
        put(&r, "ffff", end, b"other", end).unwrap();
        assert!(latest(&r, None).is_err(), "two appliances: must choose");
        assert_eq!(latest(&r, Some("ffff")).unwrap().2, b"other");
        assert!(put(&r, "../x", 1, b"", 1).is_err());
    }
}
