//! Instant recovery of VMs (contract: docs/pve-connector.md, "Instant recovery flow").
//!
//! The target VM boots on the node from qcow2 overlays (storage plugin volumes
//! `<storeid>:ir/<target>/<archive>.<device>.qcow2`) whose backing file is this
//! appliance's read-only NBD export, relayed by `ir-serve` over SSH. Guest writes
//! stay in the overlays; `qm disk move` (live drive-mirror) then copies every
//! disk to real storage and frees the overlays, after which serving stops.

use crate::backup::{read_config, read_excluded, source_name, Cluster, Kill, SshNode};
use anyhow::{bail, Context, Result};
use chunkstore::{Index, Store};
use std::collections::BTreeMap;
use std::io::{BufRead, BufReader, BufWriter};
use std::process::Stdio;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{mpsc, Mutex};
use std::time::{Duration, Instant};

/// One disk of the recovered VM, served from the snapshot's `device` index.
#[derive(Debug, PartialEq)]
pub struct IrDisk {
    /// config key, e.g. `scsi0`
    pub key: String,
    /// snapshot device / NBD export name, e.g. `drive-scsi0`
    pub device: String,
}

/// Creation parameters of the target VM plus the disks to serve.
#[derive(Debug)]
pub struct IrConfig {
    pub params: Vec<(String, String)>,
    pub disks: Vec<IrDisk>,
    /// keys left out because they were not backed up (e.g. `backup=0` disks)
    pub dropped: Vec<String>,
}

pub fn ir_volid(storage: &str, target: u32, archive: &str, device: &str) -> String {
    format!("{storage}:ir/{target}/{archive}.{device}.qcow2")
}

pub(crate) fn is_disk_key(k: &str) -> bool {
    if k == "efidisk0" || k == "tpmstate0" {
        return true;
    }
    ["ide", "sata", "scsi", "virtio"].iter().any(|p| {
        k.strip_prefix(p)
            .is_some_and(|n| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()))
    })
}

pub(crate) fn is_net_key(k: &str) -> bool {
    k.strip_prefix("net")
        .is_some_and(|n| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()))
}

/// A NIC value (VM or CT `netN`) isolated for a restore test: on `bridge`
/// (VLAN tag dropped, link up), or without one `link_down=1`.
pub fn isolate_net(v: &str, bridge: Option<&str>) -> String {
    let mut opts: Vec<String> = v
        .split(',')
        .filter(|o| !(o.starts_with("link_down=") || (bridge.is_some() && o.starts_with("tag="))))
        .map(|o| match (bridge, o.strip_prefix("bridge=")) {
            (Some(b), Some(_)) => format!("bridge={b}"),
            _ => o.to_owned(),
        })
        .collect();
    if bridge.is_none() {
        opts.push("link_down=1".into());
    }
    opts.join(",")
}

/// A NIC value with its bridge renamed by `map` (recovery plan network mapping).
pub fn map_net(v: &str, map: &BTreeMap<String, String>) -> String {
    v.split(',')
        .map(|o| match o.strip_prefix("bridge=").and_then(|b| map.get(b)) {
            Some(to) => format!("bridge={to}"),
            None => o.to_owned(),
        })
        .collect::<Vec<_>>()
        .join(",")
}

/// Hard stop (if running) and destroy with purge: restore-test guests only.
pub fn destroy_guest(api: &crate::api::Api, node: &str, kind: &str, vmid: u32) -> Result<()> {
    if api.guest_status(node, kind, vmid).map(|(r, _)| r).unwrap_or(true) {
        let stop = api
            .post_task(&format!("/nodes/{node}/{kind}/{vmid}/status/stop"), &[])
            .and_then(|upid| api.run_task(node, &upid, Duration::from_secs(300)));
        if let Err(e) = stop {
            eprintln!("stopping {kind} {vmid}: {e:#}");
        }
    }
    let upid = api
        .delete_task(&format!(
            "/nodes/{node}/{kind}/{vmid}?purge=1&destroy-unreferenced-disks=1"
        ))
        .with_context(|| format!("destroy {kind} {vmid}"))?;
    api.run_task(node, &upid, Duration::from_secs(900))
        .with_context(|| format!("destroy {kind} {vmid}"))?;
    eprintln!("destroyed {kind} {vmid}");
    Ok(())
}

/// Rewrites the backed-up `qemu-server.conf` into creation parameters for the
/// instant recovery VM: backed-up disks point at IR overlays, MAC addresses,
/// vmgenid (root-only via the API) and the SMBIOS UUID are regenerated by PVE, the cloud-init drive is
/// recreated on `target_storage`, snapshot sections, locks, `onboot` and
/// disks that were not backed up are dropped. `link_down` disconnects all NICs
/// (avoids address conflicts with the still running original).
pub fn ir_config(
    conf: &str,
    storage: &str,
    target: u32,
    archive: &str,
    devices: &[String],
    target_storage: &str,
    link_down: bool,
) -> Result<IrConfig> {
    let mut map = BTreeMap::new();
    let mut lines = Vec::new();
    for line in conf.lines() {
        if line.starts_with('[') {
            break; // snapshots / pending changes
        }
        if let Some(m) = line.strip_prefix("#qmdump#map:") {
            // map:<key>:<device>:<storage>:<format>:
            let mut p = m.split(':');
            if let (Some(k), Some(d)) = (p.next(), p.next()) {
                map.insert(k.to_owned(), d.to_owned());
            }
            continue;
        }
        if line.starts_with('#') || line.trim().is_empty() {
            continue; // description
        }
        let (k, v) = line
            .split_once(':')
            .with_context(|| format!("malformed config line '{line}'"))?;
        lines.push((k.trim(), v.trim()));
    }

    let mut out = IrConfig {
        params: Vec::new(),
        disks: Vec::new(),
        dropped: Vec::new(),
    };
    let mut push = |k: &str, v: String| out.params.push((k.to_owned(), v));
    for (k, v) in lines {
        match k {
            "meta" | "lock" | "parent" | "vmstate" | "runningmachine" | "runningcpu" | "snaptime" | "onboot"
            | "vmgenid" | "digest" => {}
            "template" => bail!("VM templates cannot be instantly recovered"),
            _ if k.starts_with("unused") => {}
            "smbios1" => {
                let rest: Vec<&str> = v.split(',').filter(|o| !o.starts_with("uuid=")).collect();
                if !rest.is_empty() {
                    push(k, rest.join(","));
                }
            }
            _ if is_net_key(k) => {
                let mut opts: Vec<String> = Vec::new();
                for (i, o) in v.split(',').enumerate() {
                    if o.starts_with("macaddr=") || (link_down && o.starts_with("link_down=")) {
                        continue;
                    }
                    // first option is `<model>=<mac>`: keep the model, PVE assigns a new MAC
                    let o = if i == 0 { o.split('=').next().unwrap_or(o) } else { o };
                    opts.push(o.to_owned());
                }
                if link_down {
                    opts.push("link_down=1".into());
                }
                push(k, opts.join(","));
            }
            _ if is_disk_key(k) => {
                if let Some(device) = map.get(k) {
                    if k == "tpmstate0" {
                        bail!("VMs with a TPM state cannot be instantly recovered (swtpm needs a local raw image)");
                    }
                    if !devices.contains(device) {
                        bail!("{k}: snapshot has no device {device}");
                    }
                    let opts = v.split(',').skip(1).filter(|o| !o.starts_with("size="));
                    let val: Vec<String> = std::iter::once(ir_volid(storage, target, archive, device))
                        .chain(opts.map(str::to_owned))
                        .collect();
                    push(k, val.join(","));
                    out.disks.push(IrDisk {
                        key: k.to_owned(),
                        device: device.clone(),
                    });
                } else if v.split(',').any(|o| o == "media=cdrom") {
                    let vol = v.split(',').next().unwrap_or_default();
                    if vol.contains("cloudinit") {
                        push(k, format!("{target_storage}:cloudinit,media=cdrom"));
                    } else {
                        push(k, v.to_owned()); // ISO or none
                    }
                } else {
                    out.dropped.push(k.to_owned());
                }
            }
            _ => push(k, v.to_owned()),
        }
    }
    if out.disks.is_empty() {
        bail!("the snapshot's configuration references no backed-up disk");
    }
    Ok(out)
}

/// `(archive, device)` of an IR volume of `target` on `storage`, from a config value.
fn parse_ir_value(value: &str, storage: &str, target: u32) -> Option<(String, String)> {
    let vol = value.split(',').next()?;
    let rest = vol.strip_prefix(&format!("{storage}:ir/{target}/"))?;
    let (archive, device) = rest.strip_suffix(".qcow2")?.split_once('.')?;
    Some((archive.to_owned(), device.to_owned()))
}

/// IR volumes still referenced by a VM config (including `unusedN`), as (key, archive, device).
pub fn ir_volumes(
    cfg: &serde_json::Map<String, serde_json::Value>,
    storage: &str,
    target: u32,
) -> Vec<(String, String, String)> {
    cfg.iter()
        .filter_map(|(k, v)| {
            let (a, d) = parse_ir_value(v.as_str()?, storage, target)?;
            Some((k.clone(), a, d))
        })
        .collect()
}

/// Sessions of one IR serve run. Every `ir-serve` child is registered so a stop
/// can kill them all; registering after the stop kills the child at once.
#[derive(Default)]
struct Sessions {
    stopped: bool,
    children: Vec<Kill>,
}

impl Sessions {
    /// false (and the child is killed) if the run is already stopping
    fn register(reg: &Mutex<Sessions>, child: Kill) -> bool {
        let mut s = reg.lock().unwrap();
        if !s.stopped {
            s.children.push(child);
        }
        !s.stopped
    }

    fn stop(reg: &Mutex<Sessions>) {
        let children = {
            let mut s = reg.lock().unwrap();
            s.stopped = true;
            std::mem::take(&mut s.children)
        };
        drop(children); // Kill: kill + reap; blocked pipe readers see EOF
    }
}

/// Keeps one idle `ir-serve` listener for `device` on the node and serves every
/// connection QEMU makes (VM start, reconnects, offline moves), each over its
/// own SSH session, until stopped. Sends one message on `ready` once the first
/// listener is published.
#[allow(clippy::too_many_arguments)]
fn serve_ir_device<'s>(
    scope: &'s std::thread::Scope<'s, '_>,
    store: &'s Store,
    ssh: &'s SshNode,
    reg: &'s Mutex<Sessions>,
    stopping: &'s AtomicBool,
    target: u32,
    archive: &'s str,
    device: &'s str,
    idx: &'s Index,
    ready: mpsc::Sender<()>,
) {
    let mut announced = false;
    let mut conn_no = 0u64;
    while !stopping.load(Ordering::SeqCst) {
        let spawned = ssh
            .cmd(&format!("ir-serve {target} {archive} {device}"))
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .spawn();
        let mut child = match spawned {
            Ok(c) => Kill(c),
            Err(e) => {
                eprintln!("ir {device}: spawn ssh: {e}");
                std::thread::sleep(Duration::from_secs(2));
                continue;
            }
        };
        let mut r = BufReader::with_capacity(1 << 20, child.0.stdout.take().unwrap());
        let w = BufWriter::with_capacity(1 << 20, child.0.stdin.take().unwrap());
        if !Sessions::register(reg, child) {
            break;
        }
        let mut line = String::new();
        if r.read_line(&mut line).is_err() || line != "listening\n" {
            if !stopping.load(Ordering::SeqCst) {
                eprintln!("ir {device}: listener failed to start; retrying");
                std::thread::sleep(Duration::from_secs(2));
            }
            continue;
        }
        if !announced {
            announced = true;
            let _ = ready.send(());
        }
        line.clear();
        if r.read_line(&mut line).is_err() || line != "accepted\n" {
            if !stopping.load(Ordering::SeqCst) {
                eprintln!("ir {device}: listener session ended; restarting");
                std::thread::sleep(Duration::from_secs(1));
            }
            continue;
        }
        conn_no += 1;
        let n = conn_no;
        eprintln!("ir {device}: connection {n} accepted");
        scope.spawn(move || {
            let res = store
                .image_reader(idx)
                .and_then(|mut img| nbd::server::serve(r, w, device, img.size(), |off, buf| img.read_at(off, buf)));
            match res {
                Ok(()) => eprintln!("ir {device}: connection {n} closed"),
                Err(e) if !stopping.load(Ordering::SeqCst) => eprintln!("ir {device}: connection {n} failed: {e}"),
                Err(_) => {}
            }
        });
    }
}

/// Timings of one instant recovery run.
pub struct IrReport {
    pub running_after: Duration,
    pub moves: Vec<(String, Duration)>,
    pub move_errors: Vec<String>,
}

impl Cluster {
    /// Instant recovery of snapshot `vm-<vmid>/<time>` as VM `target` on `node`;
    /// disks end up on `target_storage`. Returns once all disks are moved (or the
    /// VM is destroyed); serves the disks meanwhile. Options (`crate::restore`):
    /// `link_down`, `start` (without it the disks are moved while the VM is off),
    /// name / name prefix and pool; `replace` is not offered here.
    #[allow(clippy::too_many_arguments)]
    pub fn instant_recover(
        &self,
        store: &Store,
        vmid: u32,
        time: u64,
        node: &str,
        target: u32,
        target_storage: &str,
        opts: &crate::restore::RestoreOpts,
    ) -> Result<IrReport> {
        if opts.replace {
            bail!("instant recovery cannot replace the original; use a full restore");
        }
        let start = Instant::now();
        let (m, archive, plan) = self.ir_prepare(store, vmid, time, target, target_storage, opts, None)?;
        let disks: Vec<(String, String)> = plan.disks.iter().map(|d| (d.key.clone(), d.device.clone())).collect();
        self.serve_ir(store, &m, node, target, &archive, &disks, |api| {
            let id = target.to_string();
            let mut form: Vec<(&str, &str)> = vec![("vmid", id.as_str())];
            form.extend(plan.params.iter().map(|(k, v)| (k.as_str(), v.as_str())));
            let upid = api.post_task(&format!("/nodes/{node}/qemu"), &form)?;
            api.run_task(node, &upid, Duration::from_secs(600))
                .context("create VM")?;
            if opts.start {
                let upid = api.post_task(&format!("/nodes/{node}/qemu/{target}/status/start"), &[])?;
                api.run_task(node, &upid, Duration::from_secs(600))
                    .context("start VM")?;
            }
            let running_after = start.elapsed();
            if opts.start {
                eprintln!("VM {target} running after {running_after:.1?}; moving disks to {target_storage}");
            } else {
                eprintln!("VM {target} created (not started) after {running_after:.1?}; moving disks to {target_storage}");
            }

            let mut report = IrReport {
                running_after,
                moves: Vec::new(),
                move_errors: Vec::new(),
            };
            for d in &plan.disks {
                let t = Instant::now();
                let res = api
                    .post_task(
                        &format!("/nodes/{node}/qemu/{target}/move_disk"),
                        &[("disk", d.key.as_str()), ("storage", target_storage), ("delete", "1")],
                    )
                    .and_then(|upid| api.run_task(node, &upid, Duration::from_secs(7 * 86400)));
                match res {
                    Ok(()) => {
                        eprintln!("{} moved in {:.1?}", d.key, t.elapsed());
                        report.moves.push((d.key.clone(), t.elapsed()));
                    }
                    Err(e) => {
                        // keep serving: the VM depends on us until the disk is moved
                        eprintln!(
                            "moving {} failed: {e:#}\nstill serving; move the disk (qm disk move {target} {} <storage> --delete 1) or destroy the VM",
                            d.key, d.key
                        );
                        report.move_errors.push(format!("{}: {e:#}", d.key));
                    }
                }
            }
            Ok(report)
        })
    }

    /// The target VM's creation parameters for snapshot `vm-<vmid>/<time>`
    /// (excluded disks left out, name / pool from `opts`; NICs on `bridge`
    /// ([`isolate_net`]), else link down with `opts.link_down`), after checking
    /// that `target` is free and pushing the index the node plugin sizes the
    /// overlays from. Returns (manifest, archive, plan).
    #[allow(clippy::too_many_arguments)]
    fn ir_prepare(
        &self,
        store: &Store,
        vmid: u32,
        time: u64,
        target: u32,
        target_storage: &str,
        opts: &crate::restore::RestoreOpts,
        bridge: Option<&str>,
    ) -> Result<(chunkstore::Manifest, String, IrConfig)> {
        let m = store.load_manifest(&source_name(vmid), time)?;
        let mut conf = read_config(store, &m, "qemu-server.conf")?.context("snapshot has no qemu-server.conf")?;
        // excluded disks have no data to serve: the recovered VM never gets them
        if let Some(x) = read_excluded(store, &m)? {
            eprintln!("excluded from the backup, left out: {}", x.keys().join(", "));
            conf = crate::exclude::omit_config(&conf, &x.keys());
        }
        let archive = format!("nexus-{vmid}-{time}");
        let devices: Vec<String> = m.indexes.iter().filter(|n| *n != "config").cloned().collect();
        let mut plan = ir_config(
            &conf,
            &self.storage,
            target,
            &archive,
            &devices,
            target_storage,
            opts.link_down && bridge.is_none(),
        )?;
        if !plan.dropped.is_empty() {
            eprintln!("not backed up, left out: {}", plan.dropped.join(", "));
        }
        if bridge.is_some() {
            for (_, v) in plan.params.iter_mut().filter(|(k, _)| is_net_key(k)) {
                *v = isolate_net(v, bridge);
            }
        }
        let name = opts.name_for(
            crate::restore::conf_value(&conf, "name").as_deref(),
            &format!("vm-{vmid}"),
        );
        plan.params.retain(|(k, _)| k != "name");
        plan.params.push(("name".into(), name));
        if let Some(pool) = &opts.pool {
            plan.params.push(("pool".into(), pool.clone()));
        }
        if self.guest(target).is_ok() {
            bail!("VM {target} already exists");
        }
        // the node plugin sizes the overlays from the catalog
        self.push_index(store)?;
        Ok((m, archive, plan))
    }

    /// Restore test (`crate::restoretest`): boots snapshot `vm-<vmid>/<time>` as
    /// VM `target` named `name` on `node` from IR overlays that are never moved,
    /// NICs isolated (on `bridge`, else link down), runs `inside` while serving,
    /// then destroys the VM with its overlays, also when starting it failed.
    /// Errors: creating, starting or destroying the VM (`inside` keeps its own results).
    #[allow(clippy::too_many_arguments)]
    pub fn ir_session(
        &self,
        store: &Store,
        vmid: u32,
        time: u64,
        node: &str,
        target: u32,
        target_storage: &str,
        name: &str,
        bridge: Option<&str>,
        inside: &mut dyn FnMut(),
    ) -> Result<()> {
        let opts = crate::restore::RestoreOpts {
            name: Some(name.to_owned()),
            link_down: true,
            ..Default::default()
        };
        let (m, archive, plan) = self.ir_prepare(store, vmid, time, target, target_storage, &opts, bridge)?;
        let disks: Vec<(String, String)> = plan.disks.iter().map(|d| (d.key.clone(), d.device.clone())).collect();
        self.serve_ir(store, &m, node, target, &archive, &disks, |api| {
            let id = target.to_string();
            let mut form: Vec<(&str, &str)> = vec![("vmid", id.as_str())];
            form.extend(plan.params.iter().map(|(k, v)| (k.as_str(), v.as_str())));
            let upid = api.post_task(&format!("/nodes/{node}/qemu"), &form)?;
            if let Err(e) = api.run_task(node, &upid, Duration::from_secs(600)) {
                // a half-created VM goes too
                let _ = destroy_guest(api, node, "qemu", target);
                return Err(e.context("create VM"));
            }
            let started = api
                .post_task(&format!("/nodes/{node}/qemu/{target}/status/start"), &[])
                .and_then(|upid| api.run_task(node, &upid, Duration::from_secs(600)))
                .context("start VM");
            if started.is_ok() {
                inside();
            }
            let destroyed = destroy_guest(api, node, "qemu", target);
            started?;
            destroyed
        })
    }

    /// Resumes serving the IR volumes VM `target` still uses (e.g. after an
    /// appliance restart); returns when none are left or the VM is gone.
    pub fn ir_resume(&self, store: &Store, node: &str, target: u32) -> Result<()> {
        let cfg = self.api.vm_config(node, target)?;
        let vols = ir_volumes(&cfg, &self.storage, target);
        let Some((_, archive, _)) = vols.first() else {
            bail!(
                "VM {target} uses no instant recovery volumes of storage {}",
                self.storage
            );
        };
        if vols.iter().any(|(_, a, _)| a != archive) {
            bail!("VM {target} uses IR volumes of several archives");
        }
        let (vmid, time) = archive
            .strip_prefix("nexus-")
            .and_then(|r| r.split_once('-'))
            .and_then(|(v, t)| Some((v.parse::<u32>().ok()?, t.parse::<u64>().ok()?)))
            .with_context(|| format!("bad archive name {archive}"))?;
        let m = store.load_manifest(&source_name(vmid), time)?;
        let disks: Vec<(String, String)> = vols.iter().map(|(k, _, d)| (k.clone(), d.clone())).collect();
        self.serve_ir(store, &m, node, target, archive, &disks, |_| Ok(()))
    }

    /// Serves `disks` ((key, device)) while `work` runs and afterwards until VM
    /// `target` references no IR volume any more (or is gone), then stops all
    /// sessions. Moved disks no longer use the backing, so stopping is safe.
    #[allow(clippy::too_many_arguments)]
    fn serve_ir<T>(
        &self,
        store: &Store,
        m: &chunkstore::Manifest,
        node: &str,
        target: u32,
        archive: &str,
        disks: &[(String, String)],
        work: impl FnOnce(&crate::api::Api) -> Result<T>,
    ) -> Result<T> {
        let ssh = self.ssh(node)?;
        let mut idxs = Vec::new();
        for (_, device) in disks {
            if device == "config" || !m.indexes.contains(device) {
                bail!("snapshot has no device {device}");
            }
            idxs.push((device.as_str(), store.load_index(m, device)?));
        }
        let reg = Mutex::new(Sessions::default());
        let stopping = AtomicBool::new(false);
        std::thread::scope(|s| {
            let (tx, rx) = mpsc::channel();
            for (device, idx) in &idxs {
                let tx = tx.clone();
                let (reg, stopping) = (&reg, &stopping);
                s.spawn(move || serve_ir_device(s, store, ssh, reg, stopping, target, archive, device, idx, tx));
            }
            drop(tx);
            let result = (|| {
                for _ in 0..idxs.len() {
                    rx.recv_timeout(Duration::from_secs(120))
                        .context("node did not publish the IR sockets (ir-serve)")?;
                }
                let out = work(&self.api)?;
                self.wait_ir_released(node, target)?;
                Ok(out)
            })();
            stopping.store(true, Ordering::SeqCst);
            Sessions::stop(&reg);
            result
        })
    }

    /// Polls until VM `target` no longer references IR volumes or no longer exists.
    fn wait_ir_released(&self, node: &str, target: u32) -> Result<()> {
        let mut last = usize::MAX;
        loop {
            let cfg = match self.api.vm_config(node, target) {
                Ok(c) => c,
                Err(e) if self.guest(target).is_err() => {
                    eprintln!("VM {target} is gone ({e:#}); stopping");
                    return Ok(());
                }
                Err(e) => {
                    eprintln!("reading config of VM {target}: {e:#}");
                    std::thread::sleep(Duration::from_secs(5));
                    continue;
                }
            };
            let left = ir_volumes(&cfg, &self.storage, target);
            if left.is_empty() {
                return Ok(());
            }
            if left.len() != last {
                last = left.len();
                let keys: Vec<&str> = left.iter().map(|(k, _, _)| k.as_str()).collect();
                eprintln!("serving until moved: {}", keys.join(", "));
            }
            std::thread::sleep(Duration::from_secs(5));
        }
    }
}

