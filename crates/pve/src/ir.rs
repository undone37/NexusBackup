    #[test]
    fn rewrites_config() {
        let c = ir_config(CONF, "nexus", 903, "nexus-100-1760000000", &devs(), "local-lvm", false).unwrap();
        let p: BTreeMap<&str, &str> = c.params.iter().map(|(k, v)| (k.as_str(), v.as_str())).collect();
        assert_eq!(
            p["scsi0"],
            "nexus:ir/903/nexus-100-1760000000.drive-scsi0.qcow2,discard=on"
        );
        assert_eq!(
            p["virtio0"],
            "nexus:ir/903/nexus-100-1760000000.drive-virtio0.qcow2,iothread=1"
        );
        assert_eq!(p["ide2"], "local-lvm:cloudinit,media=cdrom");
        assert_eq!(p["ide0"], "local:iso/debian.iso,media=cdrom");
        assert_eq!(p["net0"], "virtio,bridge=vmbr1");
        assert_eq!(p["net1"], "e1000,bridge=vmbr0,firewall=1,link_down=0");

        assert_eq!(p["smbios1"], "manufacturer=QUNNRQ==,base64=1");
        assert_eq!(p["sshkeys"], "ssh-ed25519%20AAAA%20nexus-lab%0A");
        assert_eq!(p["boot"], "order=scsi0;net0");
        assert_eq!(p["memory"], "1024");
        for gone in [
            "vmgenid",
            "lock",
            "meta",
            "onboot",
            "parent",
            "unused0",
            "scsi1",
            "description",
        ] {
            assert!(!p.contains_key(gone), "{gone} must be dropped");
        }
        assert_eq!(c.dropped, vec!["scsi1".to_owned()]);
        assert_eq!(
            c.disks,
            vec![
                IrDisk {
                    key: "scsi0".into(),
                    device: "drive-scsi0".into()
                },
                IrDisk {
                    key: "virtio0".into(),
                    device: "drive-virtio0".into()
                }
            ]
        );
        // snapshot section ignored: exactly one scsi0
        assert_eq!(c.params.iter().filter(|(k, _)| k == "scsi0").count(), 1);
    }

