#!/usr/bin/env python3
"""Generates the low-level layer of both SDKs from the API description (issue #181).

    python3 sdk/codegen.py           write the generated files
    python3 sdk/codegen.py --check   fail if they differ from what the description gives (the sync gate)

Input: crates/web-api/openapi.json (hand-maintained, the single source of truth; crates/web-api/src/openapi.rs
keeps it covering the token allow-list and every operation named). Output, one entry per operation, named after
its `operationId`:

    sdk/python/src/nexusbackup/_operations.py   the operation table and a typed method per operation
    sdk/powershell/NexusBackup/Operations.ps1   the operation table behind Invoke-NexusBackupApi

Only the operation table is generated (method, path, parameters, body, token reachability, summary); request
and response bodies stay JSON (dicts / PSCustomObjects) as the API documents them.

Standard library only, so the gate runs anywhere Python 3.10+ is.
"""

from __future__ import annotations

import json
import keyword
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "crates/web-api/openapi.json"
PY_OUT = ROOT / "sdk/python/src/nexusbackup/_operations.py"
PS_OUT = ROOT / "sdk/powershell/NexusBackup/Operations.ps1"
METHODS = ("get", "put", "post", "delete", "patch")
HEADER = "Generated by sdk/codegen.py from crates/web-api/openapi.json. Do not edit; run: python3 sdk/codegen.py"


def strict_load(path: Path) -> dict:
    """json.load that refuses duplicate keys (json.load keeps the last one silently)."""

    def pairs(items: list) -> dict:
        out: dict = {}
        for k, v in items:
            if k in out:
                raise SystemExit(f"{path}: duplicate key {k!r}")
            out[k] = v
        return out

    return json.loads(path.read_text(), object_pairs_hook=pairs)


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).lower()
    s = re.sub(r"[^a-z0-9_]", "_", s)
    return s + "_" if keyword.iskeyword(s) or s in ("body", "self") else s


class Spec:
    def __init__(self, doc: dict) -> None:
        self.doc = doc

    def ref(self, obj: dict) -> dict:
        seen = 0
        while "$ref" in obj:
            ptr = obj["$ref"].removeprefix("#/").split("/")
            obj = self.doc
            for p in ptr:
                obj = obj[p]
            seen += 1
            if seen > 20:
                raise SystemExit("$ref loop")
        return obj

    def py_type(self, schema: dict) -> str:
        schema = self.ref(schema)
        t = schema.get("type")
        if isinstance(t, list):
            t = next((x for x in t if x != "null"), None)
        return {"integer": "int", "string": "str", "boolean": "bool", "number": "float"}.get(t or "", "Any")

    def operations(self) -> list[dict]:
        ops, ids = [], set()
        for path, item in self.doc["paths"].items():
            for method in METHODS:
                op = item.get(method)
                if op is None:
                    continue
                oid = op.get("operationId")
                if not oid:
                    raise SystemExit(f"{method.upper()} {path}: no operationId")
                if oid in ids:
                    raise SystemExit(f"operationId {oid} used twice")
                ids.add(oid)
                params: dict[tuple[str, str], dict] = {}
                for p in item.get("parameters", []) + op.get("parameters", []):
                    p = self.ref(p)
                    params[(p["in"], p["name"])] = p
                path_names = re.findall(r"\{([^}]+)\}", path)
                path_params = []
                for n in path_names:
                    p = params.get(("path", n))
                    if p is None:
                        raise SystemExit(f"{oid}: path parameter {n} not declared")
                    path_params.append({"name": n, "type": self.py_type(p.get("schema", {}))})
                query = [
                    {
                        "name": p["name"],
                        "type": self.py_type(p.get("schema", {})),
                        "required": bool(p.get("required")),
                    }
                    for (where, _), p in params.items()
                    if where == "query"
                ]
                for (where, n), _ in params.items():
                    if where not in ("path", "query"):
                        raise SystemExit(f"{oid}: {where} parameter {n} not supported by the SDKs")
                body = "none"
                if "requestBody" in op:
                    rb = self.ref(op["requestBody"])
                    if list(rb.get("content", {})) != ["application/json"]:
                        raise SystemExit(f"{oid}: request body other than application/json")
                    body = "required" if rb.get("required") else "optional"
                summary = " ".join(op.get("summary", "").split())
                ops.append(
                    {
                        "id": oid,
                        "method": method.upper(),
                        "path": path,
                        "path_params": path_params,
                        "query": query,
                        "body": body,
                        "token": op.get("x-token", True) is not False,
                        "auth": op.get("security", None) != [],
                        "summary": summary,
                    }
                )
        return ops


def py_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def py_tuple(items: list[str]) -> str:
    if len(items) == 1:
        return f"({py_str(items[0])},)"
    return "(" + ", ".join(py_str(i) for i in items) + ")"


def gen_python(spec: Spec, ops: list[dict]) -> str:
    version = spec.doc["info"]["version"]
    out = [
        f'"""{HEADER}',
        "",
        "One method per operation of the NexusBackup REST API (`Client.api`), named after the operationId in snake",
        "case. They return the decoded answer (JSON as dicts and lists, CSV as str, downloads as bytes); a job",
        "answers `{\"id\": ...}` and a request that needs approval `{\"quorum_id\": ...}`, which `Client.wait`",
        "turns into an outcome.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, NamedTuple",
        "",
        f"API_VERSION = {py_str(version)}",
        '"""`info.version` of the API description these operations were generated from."""',
        "",
        "",
        "class Operation(NamedTuple):",
        '    """One operation of the API description."""',
        "",
        "    method: str",
        "    path: str",
        "    path_params: tuple[str, ...]",
        "    query: tuple[str, ...]",
        "    body: str",
        '    """"none", "optional" or "required" (JSON)"""',
        "    token: bool",
        '    """reachable with an API token (`x-token` is not false); otherwise a person\'s session is needed"""',
        "    auth: bool",
        '    """needs a session or token (sign-in and the API description do not)"""',
        "",
        "",
        "OPERATIONS: dict[str, Operation] = {",
    ]
    for o in ops:
        fields = [
            py_str(o["method"]),
            py_str(o["path"]),
            py_tuple([p["name"] for p in o["path_params"]]),
            py_tuple([q["name"] for q in o["query"]]),
            py_str(o["body"]),
            str(o["token"]),
            str(o["auth"]),
        ]
        line = f"    {py_str(o['id'])}: Operation({', '.join(fields)}),"
        if len(line) <= 110:
            out.append(line)
        else:
            out.append(f"    {py_str(o['id'])}: Operation(")
            for f, items in zip(fields, (None, None, o["path_params"], o["query"], None, None, None)):
                if items is not None and len(f"        {f},") > 120:  # as ruff format wraps it
                    out.append("        (")
                    out.extend(f"            {py_str(i['name'])}," for i in items)
                    out.append("        ),")
                else:
                    out.append(f"        {f},")
            out.append("    ),")
    out.append("}")
    out.append("")
    out.append("")
    out.append("class Operations:")
    out.append('    """The generated methods; `Client.api` is an instance bound to a client."""')
    out.append("")
    out.append("    def _call(")
    out.append("        self, operation_id: str, path: dict[str, Any], query: dict[str, Any], body: Any")
    out.append("    ) -> Any:  # pragma: no cover - implemented by the client")
    out.append("        raise NotImplementedError")
    for o in ops:
        args = ["self"]
        for p in o["path_params"]:
            args.append(f"{snake(p['name'])}: {p['type']}")
        if o["body"] == "required":
            args.append("body: Any")
        kw = []
        if o["body"] == "optional":
            kw.append("body: Any = None")
        for q in o["query"]:
            kw.append(f"{snake(q['name'])}: {q['type']} | None = None")
        if kw:
            args.append("*")
            args.extend(kw)
        sig = f"    def {snake(o['id'])}({', '.join(args)}) -> Any:"
        out.append("")
        if len(sig) > 110:
            out.append(f"    def {snake(o['id'])}(")
            for a in args:
                out.append(f"        {a},")
            out.append("    ) -> Any:")
        else:
            out.append(sig)
        flags = []
        if not o["auth"]:
            flags.append("no authentication")
        elif not o["token"]:
            flags.append("needs a person's session (not with an API token)")
        doc = textwrap.wrap(o["summary"] or o["id"], 100)
        out.append(f'        """{doc[0]}')
        out.extend(f"        {line}" for line in doc[1:])
        out.append("")
        out.append(f"        `{o['method']} {o['path']}`" + (f": {'; '.join(flags)}." if flags else ""))
        out.append('        """')
        path_args = ", ".join(f"{py_str(p['name'])}: {snake(p['name'])}" for p in o["path_params"])
        query_args = ", ".join(f"{py_str(q['name'])}: {snake(q['name'])}" for q in o["query"])
        body_arg = "body" if o["body"] != "none" else "None"
        call = f"        return self._call({py_str(o['id'])}, {{{path_args}}}, {{{query_args}}}, {body_arg})"
        if len(call) <= 110:
            out.append(call)
            continue
        out.append("        return self._call(")
        out.append(f"            {py_str(o['id'])},")
        out.append(f"            {{{path_args}}},")
        if len(f"            {{{query_args}}},") <= 110:
            out.append(f"            {{{query_args}}},")
        else:
            out.append("            {")
            out.extend(f"                {py_str(q['name'])}: {snake(q['name'])}," for q in o["query"])
            out.append("            },")
        out.append(f"            {body_arg},")
        out.append("        )")
    return "\n".join(out) + "\n"


def ps_str(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def ps_list(items: list[str]) -> str:
    return "@(" + ", ".join(ps_str(i) for i in items) + ")"


def gen_powershell(spec: Spec, ops: list[dict]) -> str:
    version = spec.doc["info"]["version"]
    out = [
        f"# {HEADER}",
        "#",
        "# The operations of the NexusBackup REST API by operationId: Invoke-NexusBackupApi -OperationId <id> calls",
        "# any of them; the cmdlets of the module are built on it.",
        "",
        f"$script:NexusBackupApiVersion = {ps_str(version)}",
        "$script:NexusBackupOperations = [ordered]@{",
    ]
    for o in ops:
        out.append(f"    {ps_str(o['id'])} = @{{")
        out.append(f"        Method          = {ps_str(o['method'])}")
        out.append(f"        Path            = {ps_str(o['path'])}")
        out.append(f"        PathParameters  = {ps_list([p['name'] for p in o['path_params']])}")
        out.append(f"        QueryParameters = {ps_list([q['name'] for q in o['query']])}")
        out.append(f"        Body            = {ps_str(o['body'])}")
        out.append(f"        Token           = ${str(o['token']).lower()}")
        out.append(f"        Auth            = ${str(o['auth']).lower()}")
        out.append(f"        Summary         = {ps_str(o['summary'])}")
        out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> int:
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        print(__doc__, file=sys.stderr)
        return 2
    spec = Spec(strict_load(SPEC))
    ops = spec.operations()
    stale = []
    for path, text in ((PY_OUT, gen_python(spec, ops)), (PS_OUT, gen_powershell(spec, ops))):
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print(
            "SDK operation tables out of date with crates/web-api/openapi.json: "
            + ", ".join(map(str, stale))
            + "\nrun: python3 sdk/codegen.py",
            file=sys.stderr,
        )
        return 1
    print(f"{len(ops)} operations", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
